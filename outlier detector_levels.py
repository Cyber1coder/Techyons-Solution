def benchmark_validation(df):

    flags=[]

    for _,row in df.iterrows():

        key=(

            row["jobFamily_clean"],
            row["level_group"],
            row["region"]

        )

        salary=row["baseSalary_USD"]

        if key in BENCHMARKS:

            low=BENCHMARKS[key]["min"]
            high=BENCHMARKS[key]["max"]

            flags.append(

                salary<low
                or
                salary>high

            )

        else:

            flags.append(False)

    df["flag_benchmark"]=flags

    return df

