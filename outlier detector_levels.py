def user_trust_score(df):

    df = df.copy()

    trust = []

    for _, row in df.iterrows():

        score = row["consistency_score"]

        duplicate = row.get(
            "flag_duplicate",
            False
        )

        benchmark = row.get(
            "flag_benchmark",
            False
        )

        trust_score = 1.0

        if duplicate:
            trust_score -= 0.3

        if benchmark:
            trust_score -= 0.3

        if score < 0.7:
            trust_score -= 0.2

        trust.append(

            max(
                0,
                round(
                    trust_score,
                    2
                )
            )

        )

    df["user_trust"] = trust

    return df

