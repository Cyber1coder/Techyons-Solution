def final_decision(df):

    decisions=[]

    for _,row in df.iterrows():

        score=row[
            "consistency_score"
        ]

        trust=row[
            "user_trust"
        ]

        duplicate=row[
            "flag_duplicate"
        ]

        benchmark=row[
            "flag_benchmark"
        ]

        if duplicate:

            decisions.append(
                "Review"
            )

        elif benchmark:

            decisions.append(
                "Review"
            )

        elif score>0.9 and trust>0.8:

            decisions.append(
                "Approve"
            )

        elif score<0.5:

            decisions.append(
                "Reject"
            )

        else:

            decisions.append(
                "Review"
            )

    df["decision"]=decisions

    return df

